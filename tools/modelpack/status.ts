/**
 * Every AI model we have paid for, and whether it is used (owner, 2026-10-18: "these are relatively expensive to make
 * and we dont want to waste any by creating them and not using them"). Writes models/GLB-STATUS.md:
 *
 *   source GLB (in $INCOMING_DIR)  →  in models/sf-models.json?  →  packed into the index (LODs)?  →  placed by a project?
 *
 * "Placed" reads the projects that use the index: cityengine's public/landmarks/*-statues.json entries with
 * `asset: <id>` ($CITYENGINE_DIR, default the checkout beside this repo). Run after adding or packing models:
 *
 *   node tools/modelpack/status.ts
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..', '..')
const CITY = process.env.CITYENGINE_DIR || resolve(ROOT, '..', 'cityengine')
const INCOMING = process.env.INCOMING_DIR || join(CITY, 'incoming_assets')

const spec = JSON.parse(readFileSync(join(ROOT, 'models', 'sf-models.json'), 'utf8')) as { models: { id: string; file: string; name: string }[] }
const index = JSON.parse(readFileSync(join(ROOT, 'indexes', 'asset-index-assetkit-models-sf.json'), 'utf8')) as
  { assets: { id: string; assetFiles: { lod?: number; isDeleted?: boolean; isProd?: boolean }[] }[] }
const placed = new Map<string, string[]>()
const lm = join(CITY, 'public', 'landmarks')
if (existsSync(lm)) {
  for (const f of readdirSync(lm).filter((n) => n.endsWith('-statues.json'))) {
    for (const e of JSON.parse(readFileSync(join(lm, f), 'utf8')) as { asset?: string; name?: string }[]) {
      if (e.asset) placed.set(e.asset, [...(placed.get(e.asset) ?? []), `cityengine ${f}`])
    }
  }
}

const files = existsSync(INCOMING) ? readdirSync(INCOMING).filter((n) => n.toLowerCase().endsWith('.glb')).sort() : []
const byFile = new Map(spec.models.map((m) => [m.file, m]))
const rows: string[] = []
let used = 0, packedOnly = 0, waiting = 0
for (const f of files) {
  const m = byFile.get(f)
  const a = m ? index.assets.find((x) => x.id === m.id) : undefined
  const lods = a ? a.assetFiles.filter((x) => x.isProd && !x.isDeleted && x.lod !== undefined).length : 0
  const where = m ? placed.get(m.id) : undefined
  const state = where ? 'PLACED' : lods ? 'packed, NOT PLACED' : m ? 'described, not packed' : 'NOT STARTED'
  if (where) used++
  else if (lods) packedOnly++
  else waiting++
  rows.push(`| ${f} | ${m?.id ?? '—'} | ${state} | ${lods || '—'} | ${where?.join(', ') ?? '—'} |`)
}
for (const m of spec.models) if (!files.includes(m.file)) rows.push(`| ${m.file} (source not in incoming_assets) | ${m.id} | ${placed.has(m.id) ? 'PLACED' : 'packed, NOT PLACED'} | — | ${placed.get(m.id)?.join(', ') ?? '—'} |`)

writeFileSync(join(ROOT, 'models', 'GLB-STATUS.md'), `# AI model GLBs: are we using them?

Generated by \`node tools/modelpack/status.ts\` (${new Date().toISOString().slice(0, 10)}) — do not edit by hand. Every source GLB in
\`${INCOMING.replace(process.env.HOME ?? '~', '~')}\`, whether it is described in models/sf-models.json, packed into LODs in the
assetkit-models-sf index (and so in the bucket), and placed by a project.

**${files.length} GLBs: ${used} placed, ${packedOnly} packed but not placed, ${waiting} not yet packed.**

| source GLB | asset id | state | LODs | placed in |
|---|---|---|---|---|
${rows.join('\n')}
`)
console.log(`models/GLB-STATUS.md: ${files.length} GLBs, ${used} placed, ${packedOnly} packed but not placed, ${waiting} not yet packed`)
